/**
 * Detecta automáticamente la marca fabricante de un modelo automotriz
 */
export function obtenerMarcaVehiculo(nombreModelo) {
  if (!nombreModelo) return 'General';
  const clean = nombreModelo.toLowerCase().trim();

  // 1. Si ya viene con el prefijo de la marca
  const marcasPrincipales = [
    'Toyota', 'Chevrolet', 'Ford', 'Hyundai', 'Chery', 'Mitsubishi', 
    'Nissan', 'Renault', 'Honda', 'Mazda', 'Jeep', 'Kia', 
    'Volkswagen', 'Fiat', 'Dodge', 'Daewoo', 'Venirauto'
  ];
  for (const m of marcasPrincipales) {
    if (clean.startsWith(m.toLowerCase() + ' ')) return m;
  }

  // 2. Coincidencia exacta o contenida en diccionario
  for (const [key, marca] of Object.entries(MARCAS_POR_VEHICULO)) {
    if (clean === key || clean.includes(key)) {
      return marca;
    }
  }

  return 'Otras Marcas';
}

/**
 * Extrae modelos individuales a partir de textos compuestos separados por barras o comas
 * (Ej: "4Runner / Meru / Prado" -> ["4Runner", "Meru", "Prado"])
 */
export function desglosarModelosVehiculo(rawString) {
  if (!rawString) return [];
  return rawString
    .split(/[\/,]/)
    .map(s => s.trim())
    .filter(s => s.length > 0 && s !== 'Universal' && s !== 'General');
}

/**
 * Cuenta cuántos repuestos en el inventario son compatibles con un modelo de vehículo
 * Realiza coincidencia inteligente parcial (ej: "4Runner" coincide con "4Runner / Meru / Prado")
 */
export function contarRepuestosPorModelo(modelo, productos = []) {
  if (!modelo || !productos.length) return 0;
  const norm = modelo.toLowerCase().trim();
  // Quitar prefijo de marca si lo tiene (ej: "Toyota 4Runner" -> "4runner")
  const cleanMod = norm.replace(/^(toyota|chevrolet|ford|hyundai|mitsubishi|nissan|renault|honda|mazda|jeep|kia|volkswagen|fiat|chery|dodge|daewoo|venirauto)\s+/i, '').trim();

  return productos.filter(p => {
    const modProd = (p.modelo_vehiculo || '').toLowerCase();
    const desc = (p.descripcion || '').toLowerCase();
    return modProd.includes(cleanMod) || desc.includes(cleanMod);
  }).length;
}
